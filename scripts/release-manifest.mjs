import { promises as fs } from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
const serverText = await fs.readFile(path.join(root, 'server/index.mjs'), 'utf8');
const routes = [...new Set([...serverText.matchAll(/pathname === '([^']+)'/g)].map(match => match[1]))].sort();
const manifest = { generatedAt: new Date().toISOString(), name: pkg.name, version: pkg.version, scripts: Object.keys(pkg.scripts), routeCount: routes.length, routeHash: crypto.createHash('sha256').update(routes.join('\n')).digest('hex'), releaseSeed: 'runtime/data/db.seed.json', releaseReadiness: { localPackage: 'verified by npm run verify:release', productionServer: 'manual verification required', productionDomain: 'manual verification required', externalIntegrations: 'manual verification required' } };
await fs.mkdir(path.join(root, 'docs/current'), { recursive: true });
await fs.writeFile(path.join(root, 'docs/current/RELEASE_MANIFEST.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify(manifest, null, 2));
