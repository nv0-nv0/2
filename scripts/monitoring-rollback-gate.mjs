import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const server = fs.readFileSync(path.join(root, 'server/index.mjs'), 'utf8');
const checks = [];
const add = (name, ok, details='') => checks.push({ name, ok: Boolean(ok), details });
add('health-endpoints', server.includes('/healthz') && server.includes('/readyz'));
add('verify-prod-script', Boolean(pkg.scripts['verify:prod']));
add('runtime-backup-script', Boolean(pkg.scripts['backup:runtime']));
add('restore-latest-script', Boolean(pkg.scripts['restore:latest']));
add('restore-drill-script', Boolean(pkg.scripts['restore:drill']));
add('rollback-runbook', fs.existsSync(path.join(root, 'docs/ROLLBACK.md')));
const failures = checks.filter(item => !item.ok);
const report = { ok: failures.length === 0, contract: 'clean-baseline-monitoring-rollback', checkedAt: new Date().toISOString(), checks, failures, rollbackTriggers: ['/readyz failure','5xx spike','core diagnosis flow failure','payment webhook verification failure','storage connection failure'] };
fs.mkdirSync(path.join(root, 'docs/current'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/current/MONITORING_ROLLBACK_AUDIT.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
if (failures.length) process.exit(1);
