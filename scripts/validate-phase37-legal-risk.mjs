import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(new URL('..', import.meta.url).pathname);
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const checks=[]; const add=(name, ok, detail={})=>checks.push({name,ok:Boolean(ok),...detail});
const server=read('server/index.mjs');
const checkout=read('apps/public/checkout/index.html')+'\n'+read('apps/public/checkout/app.js');
const privacy=read('apps/public/privacy/index.html');
const terms=read('apps/public/terms/index.html');
const refund=read('apps/public/refund/index.html');
const biz=read('apps/public/business-info/index.html');
const pkg=JSON.parse(read('package.json'));
for (const token of ['처리하는 개인정보 항목','처리 목적','보유 기간 및 파기','제3자 제공 및 처리위탁','정보주체 권리','안전성 확보조치','쿠키 및 자동수집 장치']) add(`privacy:${token}`, privacy.includes(token));
for (const bad of ['buyerName','buyerPhone','buyerAddress','registerName','registerCompany']) add(`minimize:no-${bad}`, !server.includes(bad) && !checkout.includes(bad));
for (const token of ['deliveryConsent','디지털 산출물 즉시 제공','청약철회가 제한될 수 있음']) add(`checkout:${token}`, checkout.includes(token));
add('server:delivery-required', server.includes('deliveryConsent') && server.includes('디지털 산출물 제공 및 청약철회 제한'));
for (const token of ['법률 자문','법률 대리','보조도구']) add(`terms-disclaimer:${token}`, terms.includes(token) || server.includes(token));
for (const token of ['표시·광고 또는 계약 내용과 다르게 제공','관계 법령상 권리','서비스 제공 전']) add(`refund:${token}`, refund.includes(token) || terms.includes(token));
for (const token of ['통신판매업 신고번호','호스팅 제공자','NV0_MAIL_ORDER_REGISTRATION_NUMBER']) add(`business:${token}`, biz.includes(token) || server.includes(token));
add('release-gate:mail-order', server.includes('mail_order_registration'));
add('package:phase37-script', Boolean(pkg.scripts?.['validate:phase37']));
add('docs:report', fs.existsSync(path.join(root,'docs/PHASE37_LEGAL_RISK_HARDENING_REPORT_20260425_KO.md')));
const report={generatedAt:new Date().toISOString(),phase:'phase37-legal-risk-hardening',ok:checks.every(c=>c.ok),total:checks.length,passed:checks.filter(c=>c.ok).length,failed:checks.filter(c=>!c.ok).length,checks};
fs.writeFileSync(path.join(root,'docs/PHASE37_LEGAL_RISK_VALIDATION_20260425.json'), JSON.stringify(report,null,2));
console.log(JSON.stringify({ok:report.ok,passed:report.passed,failed:report.failed,report:'docs/PHASE37_LEGAL_RISK_VALIDATION_20260425.json'}, null, 2));
process.exit(report.ok?0:1);
