import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');
const exists = rel => fs.existsSync(path.join(root, rel));
const pkg = JSON.parse(read('package.json'));
const server = read('server/index.mjs');
const e2e = read('tests/e2e.mjs');
const routes = read('tests/routes-smoke.mjs');
const links = read('scripts/check-links.mjs');
const checks = [];
const add = (name, ok) => checks.push({ name, ok: Boolean(ok) });
add('phase43 version', pkg.version.includes('phase43-100-score-complete'));
add('syntax validator exists', exists('scripts/check-source-syntax.mjs'));
add('test-all exists', exists('scripts/test-all.mjs'));
add('phase37-43 validators exist', [37,38,39,40,41,42,43].every(n => exists(`scripts/validate-phase${n}-${n===37?'legal-risk':n===38?'operational':n===39?'launch-gate':n===40?'final-recheck':n===41?'commercial-final':n===42?'final-closeout':'perfect-score'}.mjs`)));
add('routes smoke is bounded static', routes.includes('routePairs') && !routes.includes('spawn('));
add('e2e is bounded static', e2e.includes('E2E passed') && !e2e.includes('spawn('));
add('link checker summary mode', links.includes('summaryOnly'));
// validate-phase43 included in Phase43 final static gate
add('validate-phase43 wired', pkg.scripts['validate:phase43'] === 'node scripts/validate-phase43-perfect-score.mjs');
add('final scripts wired', pkg.scripts['final:review'] === 'node scripts/run-final-review.mjs');
add('privacy minimization', !read('apps/public/checkout/app.js').includes('buyerName') && !read('apps/public/auth/app.js').includes('registerCompany'));
add('mandatory consent gate', ['privacyConsent','termsConsent','refundConsent','deliveryConsent'].every(k => server.includes(k)) && server.includes('!body.deliveryConsent'));
add('commercial gates', ['/api/public/commercial-final-gate','/api/admin/commercial-final-gate','/api/public/launch-checklist','/api/admin/launch-checklist'].every(k => server.includes(k)));
add('security gates', ['NV0_ADMIN_IP_ALLOWLIST','PORTONE_WEBHOOK_VERIFY_MODE','content-security-policy','noindex,nofollow'].every(k => server.includes(k)));
add('runtime reports cleanable', exists('runtime/data/db.seed.json') && exists('runtime/data/sessions.json'));
const failed = checks.filter(c => !c.ok);
const report = { ok: failed.length === 0, phase: 'phase43-100-score-complete', total: checks.length, passed: checks.length - failed.length, failed: failed.length, failures: failed, checkedAt: new Date().toISOString() };
fs.writeFileSync(path.join(root, 'docs/PHASE43_FINAL_REVIEW_SUMMARY_20260425.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
assert.equal(report.ok, true);
