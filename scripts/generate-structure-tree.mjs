import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const TREE_IGNORE = new Set(['.git', 'node_modules', '.DS_Store']);
const STRUCTURE_LIMITS = {
  maxDepth: 4,
  maxChildrenPerDir: 80
};
const TOP_LEVEL_ORDER = [
  '.github', 'apps', 'server', 'shared', 'scripts', 'tests', 'docs', 'deploy', 'runtime', 'artifacts'
];
const AREA_NOTES = new Map([
  ['apps', '공개/관리자 화면 정적 리소스와 페이지 진입점'],
  ['server', 'API 서버, 데이터 저장소, 상품 엔진/에이전트, 발행 파이프라인'],
  ['shared', '공통 UI/CSS/HTML 유틸과 대시보드 shared 스타일'],
  ['scripts', '상용화 검증, 구조 트리 생성, 배포/보안/링크 검사'],
  ['tests', '회귀 테스트, 라우트 스모크, E2E, 결제/보안 검증'],
  ['docs', '상용화 리포트, 감사 JSON, 구조/운영 문서'],
  ['deploy', '배포 보조 설정'],
  ['runtime', '로컬 실행 상태/백업/데모 데이터 저장 영역'],
  ['artifacts', '검수 산출 이미지와 스냅샷'],
  ['.github', 'CI/CD 워크플로']
]);
function exists(rel) {
  return fs.existsSync(path.join(ROOT, rel));
}
function statSafe(abs) {
  try { return fs.statSync(abs); } catch { return null; }
}
function sortedEntries(abs, rel = '') {
  const entries = fs.readdirSync(abs, { withFileTypes: true })
    .filter((entry) => !TREE_IGNORE.has(entry.name))
    .filter((entry) => !(rel === 'runtime' && entry.name === 'backups'))
    .sort((a, b) => {
      const aIdx = TOP_LEVEL_ORDER.indexOf(a.name);
      const bIdx = TOP_LEVEL_ORDER.indexOf(b.name);
      if (rel === '' && aIdx !== -1 && bIdx !== -1) return aIdx - bIdx;
      if (rel === '' && aIdx !== -1) return -1;
      if (rel === '' && bIdx !== -1) return 1;
      if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
      return a.name.localeCompare(b.name, 'en');
    });
  return entries.slice(0, STRUCTURE_LIMITS.maxChildrenPerDir);
}
function buildTree(abs, rel = '', depth = 0) {
  const node = {
    name: rel ? path.basename(rel) : path.basename(ROOT),
    path: rel || '.',
    type: statSafe(abs)?.isDirectory() ? 'dir' : 'file'
  };
  if (node.type === 'dir') {
    node.note = AREA_NOTES.get(rel) || AREA_NOTES.get(node.name) || '';
    if (depth < STRUCTURE_LIMITS.maxDepth) {
      node.children = sortedEntries(abs, rel).map((entry) => {
        const childRel = rel ? path.posix.join(rel, entry.name) : entry.name;
        return buildTree(path.join(abs, entry.name), childRel, depth + 1);
      });
    }
  } else {
    node.size = statSafe(abs)?.size || 0;
  }
  return node;
}
function treeLines(node, prefix = '', isLast = true, depth = 0) {
  const connector = depth === 0 ? '' : (isLast ? '└── ' : '├── ');
  const note = node.note ? ` — ${node.note}` : '';
  const line = `${prefix}${connector}${node.name}${node.type === 'dir' ? '/' : ''}${note}`;
  const nextPrefix = depth === 0 ? '' : `${prefix}${isLast ? '    ' : '│   '}`;
  const children = node.children || [];
  return [line, ...children.flatMap((child, index) => treeLines(child, nextPrefix, index === children.length - 1, depth + 1))];
}
function countFiles(dir) {
  let files = 0;
  let dirs = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (TREE_IGNORE.has(entry.name)) continue;
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      dirs += 1;
      const nested = countFiles(abs);
      files += nested.files;
      dirs += nested.dirs;
    } else {
      files += 1;
    }
  }
  return { files, dirs };
}
function keyMatrix() {
  return [
    ['공개 포털', 'apps/public/portal/index.html', '내 사이트 대시보드 HTML 진입점'],
    ['대시보드 스타일', 'shared/portal-phase283-dashboard.css', '승인된 SaaS 대시보드 UI 전역 스타일'],
    ['포털 동작', 'apps/public/portal/app.js', '점수 게이지, 저장 사이트, 인사이트, 계정 상태 동적 연결'],
    ['제품 에이전트', 'server/core/product-agent-suite.mjs', '제품 컨텍스트·인사이트 생성·20분 자동 발행·감사 에이전트'],
    ['서버 라우터', 'server/index.mjs', '공개/관리자 API와 정적 페이지 서빙'],
    ['상용 검증', 'scripts/validate-phase284-package-100.mjs', '이전 100점 납품 기준 검증'],
    ['구조 최적화 검증', 'scripts/validate-phase285-structure-optimization.mjs', '구조 트리와 phase285 보강 검증']
  ];
}
function writeOutputs() {
  const tree = buildTree(ROOT);
  const summary = countFiles(ROOT);
  const lines = treeLines(tree);
  const matrix = keyMatrix();
  fs.mkdirSync(path.join(ROOT, 'docs/current'), { recursive: true });
  const json = {
    ok: true,
    generatedAt: new Date().toISOString(),
    root: path.basename(ROOT),
    limits: STRUCTURE_LIMITS,
    summary,
    keyFiles: matrix.map(([area, file, role]) => ({ area, file, role, exists: exists(file) })),
    tree
  };
  fs.writeFileSync(path.join(ROOT, 'docs/current/PROJECT_STRUCTURE_TREE.json'), JSON.stringify(json, null, 2));
  const md = `# VERIDION Project Structure Tree\n\n` +
    `Generated by \`npm run structure:tree\`.\n\n` +
    `## Package Summary\n\n` +
    `- Root: \`${json.root}\`\n` +
    `- Directories: ${summary.dirs}\n` +
    `- Files: ${summary.files}\n` +
    `- Tree depth shown: ${STRUCTURE_LIMITS.maxDepth}\n\n` +
    `## Optimized Responsibility Map\n\n` +
    `| Area | File | Responsibility |\n|---|---|---|\n` +
    matrix.map(([area, file, role]) => `| ${area} | \`${file}\` | ${role} |`).join('\n') +
    `\n\n## Structure Tree\n\n\`\`\`text\n${lines.join('\n')}\n\`\`\`\n\n` +
    `## Operating Rule\n\n` +
    `- Public page-specific retired CSS references are avoided; dashboard CSS is served from \`shared/portal-phase283-dashboard.css\`.\n` +
    `- Portal dynamic IDs are preserved so existing JS behavior remains stable.\n` +
    `- Product-agent insight publication remains connected to the 20-minute cadence validator.\n` +
    `- Phase285 validation must pass after generating this tree.\n`;
  fs.writeFileSync(path.join(ROOT, 'docs/PROJECT_STRUCTURE_TREE.md'), md);
  console.log(JSON.stringify({ ok: true, summary, output: ['docs/PROJECT_STRUCTURE_TREE.md', 'docs/current/PROJECT_STRUCTURE_TREE.json'] }, null, 2));
}
writeOutputs();
