import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = rel => readFileSync(path.join(root, rel), 'utf8');
const exists = rel => existsSync(path.join(root, rel));
const checks = [];
const add = (name, ok, detail = '') => checks.push({ name, ok: Boolean(ok), detail });
const pkg = JSON.parse(read('package.json'));
const server = read('server/index.mjs');
const env = read('.env.example');
const readme = read('README.md');
add('phase42 package version marker', pkg.version.includes('phase42-final-closeout-complete') || pkg.version.includes('phase43-100-score-complete'));
add('phase42 server release marker', server.includes('phase42-final-closeout-complete'));
add('bounded final review runner', exists('scripts/run-final-review.mjs') && pkg.scripts['final:review'] === 'node scripts/run-final-review.mjs');
add('phase42 validator wired', pkg.scripts['validate:phase42'] === 'node scripts/validate-phase42-final-closeout.mjs');
add('legacy final review retained', Boolean(pkg.scripts['final:review:legacy']));
add('phase42 work order exists', exists('docs/PHASE42_FINAL_CLOSEOUT_WORK_ORDER_20260425_KO.md'));
add('phase42 report exists', exists('docs/PHASE42_FINAL_CLOSEOUT_COMPLETION_REPORT_20260425_KO.md'));
add('commercial final gate remains wired', server.includes('/api/public/commercial-final-gate') && server.includes('/api/admin/commercial-final-gate'));
add('launch checklist remains wired', server.includes('/api/public/launch-checklist') && server.includes('/api/admin/launch-checklist'));
add('strict webhook gate remains', server.includes('webhook_signature_strict') && server.includes('NV0_PORTONE_WEBHOOK_SECRET'));
add('smtp false success blocked', server.includes('blocked_no_smtp_url') && !server.includes('no_smtp_url_marked_sent'));
add('admin ip gate remains', server.includes('NV0_ADMIN_IP_ALLOWLIST') && server.includes('admin_ip_allowlist'));
add('noindex remains on private routes', server.includes('noindex,nofollow') && server.includes('Disallow: /portal'));
add('env has production-only values documented', ['NV0_PUBLIC_BASE_URL=https://nv0.kr','NV0_SMTP_URL=','NV0_PORTONE_WEBHOOK_SECRET=','NV0_ADMIN_IP_ALLOWLIST='].every(k => env.includes(k)));
add('env does not use example.com', !/example\.com/.test(env));
add('readme references final review command', readme.includes('npm run final:review'));
const failed = checks.filter(c => !c.ok);
const report = { ok: failed.length === 0, phase: 'phase42-final-closeout-complete', total: checks.length, passed: checks.length - failed.length, failed: failed.length, failures: failed, checkedAt: new Date().toISOString() };
writeFileSync(path.join(root, 'docs/PHASE42_FINAL_CLOSEOUT_VALIDATION_20260425.json'), JSON.stringify(report, null, 2));
if (failed.length) { console.error(JSON.stringify(report, null, 2)); process.exit(1); }
console.log(JSON.stringify(report, null, 2));
