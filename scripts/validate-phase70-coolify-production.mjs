import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const exists = p => fs.existsSync(path.join(root, p));
const checks = [];
const add = (name, ok, detail = '') => checks.push({ name, ok: Boolean(ok), ...(detail ? { detail } : {}) });
const dockerfile = read('Dockerfile');
const compose = read('docker-compose.yml');
const entrypoint = read('deploy/entrypoint.sh');
const pkg = JSON.parse(read('package.json'));
add('dockerfile:no-copy-runtime', !/COPY\s+runtime\b/i.test(dockerfile), 'runtime must be created/mounted, not copied from build context');
add('dockerfile:runtime-env', dockerfile.includes('NV0_RUNTIME_DIR=/app/runtime'));
add('dockerfile:volume-runtime', dockerfile.includes('VOLUME ["/app/runtime"]'));
add('dockerfile:direct-cmd', dockerfile.includes('CMD ["node", "server/index.mjs"]'));
add('dockerfile:healthcheck-healthz', dockerfile.includes('/healthz'));
add('compose:runtime-volume-mounted', compose.includes('nv0_runtime:/app/runtime'));
add('compose:runtime-volume-declared', /volumes:\s*[\s\S]*nv0_runtime:/m.test(compose));
add('compose:postgres-volume', compose.includes('nv0_postgres:/var/lib/postgresql/data'));
add('compose:redis-volume', compose.includes('nv0_redis:/data'));
add('compose:readyz-healthcheck', compose.includes('/readyz'));
add('compose:no-broken-env-lines', !/^NV0_/m.test(compose), 'every env key must be nested under environment');
add('compose:required-secret-guards', compose.includes('${NV0_PORTONE_API_SECRET:?') && compose.includes('${POSTGRES_PASSWORD:?'));
add('entrypoint:optional-preflight', entrypoint.includes('NV0_RUN_PREFLIGHT') && entrypoint.includes('exec node server/index.mjs'));
add('package:phase70-version', /phase70/.test(pkg.version));
add('runtime:empty-uploads', exists('runtime/uploads') && fs.readdirSync(path.join(root, 'runtime/uploads')).length === 0);
add('runtime:empty-backups', exists('runtime/backups') && fs.readdirSync(path.join(root, 'runtime/backups')).length === 0);
add('runtime:empty-reports', exists('runtime/reports') && fs.readdirSync(path.join(root, 'runtime/reports')).length === 0);
add('runtime:sessions-empty', exists('runtime/data/sessions.json') && read('runtime/data/sessions.json').trim() === '[]');
const failed = checks.filter(c => !c.ok);
const report = { ok: failed.length === 0, phase: 'phase70-coolify-production-final', score: failed.length === 0 ? 100 : Math.max(0, 100 - failed.length * 5), passed: checks.length - failed.length, total: checks.length, failed, checkedAt: new Date().toISOString() };
fs.writeFileSync(path.join(root, 'docs/PHASE70_COOLIFY_PRODUCTION_FINAL_VALIDATION_20260425.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
process.exit(report.ok ? 0 : 1);
