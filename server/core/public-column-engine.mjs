    boardType: 'cta',
    boardPurpose: 'cta',
    category: 'CTA 칼럼',
    audienceHook: seed.audienceHook,
    primaryKeyword: seed.primaryKeyword,
    visibility: 'public',
    createdAt: offsetIso(index, now),
    summary: seed.summary,
