function offsetIso(index = 0, now = Date.now()) {
  return new Date(now - index * 20 * MINUTE_MS).toISOString();
}

function buildBody(seed) {
  const sections = [
    ...seed.interest,
    seed.cta,
    seed.support
  ];
  return sections.map(([heading, text]) => `${heading}\n${text}`).join('\n\n');
}

