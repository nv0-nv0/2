    manualBoundaries: ['로그인 후 화면', '외부 결제창', '자바스크립트 전용 렌더링 화면', '접근 차단 또는 timeout 페이지', '업종별 법률 판단', '사업자·통신판매업 신고번호의 행정기관 진위 확인', '광고 표현의 최종 법률 검토'],
