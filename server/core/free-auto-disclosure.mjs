export function buildAutomatedActionPlan({ findings = [], evidenceSummary = {}, disclosure = {} } = {}) {
  const sorted = [...findings].sort((a, b) => Number(b.severity || 0) - Number(a.severity || 0));
  const automaticFixes = sorted.filter(item => item.autoFixEligible !== false && item.manualReviewRequired !== true).slice(0, 6).map((item, index) => ({
    order: index + 1,
    mode: 'auto_draft',
    findingCode: item.code,
    title: item.title,
    sourcePages: item.sourcePages || [],
    patchSummary: item.recommendation || '고객이 확인해야 할 안내 문구를 버튼 주변과 푸터에 보강합니다.',
    operatorNotice: '자동 생성 초안입니다. 실제 반영 전 운영 정책과 맞는지 확인하세요.'
  }));
  const manualReviews = sorted.filter(item => item.manualReviewRequired === true).slice(0, 8).map((item, index) => ({
    order: index + 1,
    mode: 'manual_review_required',
    findingCode: item.code,
    title: item.title,
    reason: item.limitation || '자동 확정이 위험한 항목입니다.',
    sourcePages: item.sourcePages || []
  }));
  return {
    mode: 'auto_first_manual_boundary',
    summary: '자동 처리 가능한 항목은 수정 후보까지 생성하고, 자동 확정 불가 항목은 직접 확인 목록으로 분리했습니다.',
    automaticFixes,
    manualReviews,
    autoNextSteps: ['확인된 P0/P1 항목을 우선순위대로 정리합니다.', '자동 수정 후보 문구를 생성합니다.', '실패한 후보 URL은 직접 확인 목록으로 넘깁니다.', '재진단 시 같은 기준으로 결과를 비교합니다.'],
    coverageNotice: evidenceSummary?.disclaimer || disclosure?.clearNotice || '공개 페이지 기준 예비 점검입니다.',
    requiresOperatorApproval: true
  };
}
